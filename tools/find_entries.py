#!/usr/bin/env python3
"""Lists the functions Ghidra merged into their neighbours, as entries.

Usage: python3 -I tools/find_entries.py DarkSoulsII.exe symbols/darksouls2 > manifest/darksouls2.entries

Arxan puts junk bytes between functions, and Ghidra then often takes a
function for a chunk of the one before it: the function has no entry of
its own, and a call through a pointer to it reaches unlifted code. A
function start here is an address the image holds as a pointer (a dword
anywhere outside .text, at any alignment, or an immediate in an
instruction) that begins `push ebp; mov ebp, esp` on a 16-byte boundary
and is not already an entry in functions.tsv.

Arxan also turns switches into `push dword [table + reg*4]; ret`: no jump
table Ghidra sees, so their cases are neither functions nor jump-table
targets. Each table's entries are taken as entries too, read while they
point into .text within 32 KiB of the first (the bound check is hidden).
Disassembly by objdump (AT&T syntax; OBJDUMP overrides).
"""
import os
import re
import struct
import subprocess
import sys


def main():
    exe, symbols = sys.argv[1], sys.argv[2]
    data = open(exe, 'rb').read()
    pe = struct.unpack_from('<I', data, 0x3C)[0]
    base = struct.unpack_from('<I', data, pe + 24 + 28)[0]
    n = struct.unpack_from('<H', data, pe + 6)[0]
    opt = struct.unpack_from('<H', data, pe + 20)[0]
    secs = []
    for i in range(n):
        o = pe + 24 + opt + 40 * i
        name = data[o:o + 8].rstrip(b'\0').decode()
        vsize, va, rsize, raw = struct.unpack_from('<IIII', data, o + 8)
        secs.append((name, base + va, rsize, raw))

    def at(va, k):
        for _, sva, rsize, raw in secs:
            if sva <= va and va + k <= sva + rsize:
                return data[raw + va - sva:raw + va - sva + k]
        return b''

    text = next(s for s in secs if s[0] == '.text')
    tlo, thi = text[1], text[1] + text[2]
    known = set()
    for line in open(os.path.join(symbols, 'functions.tsv')).read().splitlines()[1:]:
        known.add(int(line.split('\t')[0], 16))

    def start(t):
        return (tlo <= t < thi and t % 16 == 0 and t not in known
                and at(t, 3) == b'\x55\x8b\xec')

    found = set()
    for name, sva, rsize, raw in secs:
        if name == '.text':
            continue
        blob = data[raw:raw + rsize]
        for i in range(len(blob) - 3):
            t = struct.unpack_from('<I', blob, i)[0]
            if start(t):
                found.add(t)
    tro = text[3]
    for m in re.finditer(rb'\xff\x34[\x85\x8d\x95\x9d\xad\xb5\xbd].{4}\xc3',
                         data[tro:tro + text[2]], re.S):
        table = struct.unpack_from('<I', data, tro + m.start() + 3)[0]
        first = None
        for i in range(256):
            e = at(table + 4 * i, 4)
            if len(e) < 4:
                break
            t = struct.unpack('<I', e)[0]
            if first is None:
                first = t
            if not (tlo <= t < thi) or abs(t - first) > 0x8000:
                break
            if t not in known:
                found.add(t)
    tool = os.environ.get('OBJDUMP', 'objdump')
    dis = subprocess.run([tool, '-d', '--no-show-raw-insn', exe], capture_output=True,
                         text=True, check=True).stdout
    for m in re.finditer(r'\$0x([0-9a-f]{6,8})\b', dis):
        t = int(m.group(1), 16)
        if start(t):
            found.add(t)

    print('# Generated by tools/find_entries.py: function starts Ghidra merged into')
    print('# their neighbours (Arxan junk between functions), found as pointers,')
    print('# and the cases of switches Arxan turned into push [table + reg*4]; ret.')
    for t in sorted(found):
        print('entry %08X' % t)


if __name__ == '__main__':
    main()
